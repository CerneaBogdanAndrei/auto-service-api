-- =============================================================================
-- V1: initial schema for the auto service API.
--
-- Business rules are enforced in the service layer; the constraints below are a
-- safety net that keeps the data consistent even under concurrent requests.
-- History is never deleted implicitly: every foreign key is RESTRICT, except the
-- part lines of an intervention, which are owned by (and live and die with) it.
-- =============================================================================

-- Required for the EXCLUDE constraint that mixes "=" (bigint) and "&&" (range).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- -----------------------------------------------------------------------------
-- Users
-- -----------------------------------------------------------------------------
CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'OWNER', 'EMPLOYEE'))
);

CREATE UNIQUE INDEX uq_users_username ON users (lower(username));

-- -----------------------------------------------------------------------------
-- Clients
-- -----------------------------------------------------------------------------
CREATE TABLE clients
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    phone      VARCHAR(20)  NOT NULL,
    email      VARCHAR(254) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_clients_email ON clients (lower(email));

-- -----------------------------------------------------------------------------
-- Vehicles
-- -----------------------------------------------------------------------------
CREATE TABLE vehicles
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        BIGINT      NOT NULL,
    vin              VARCHAR(17) NOT NULL,
    license_plate    VARCHAR(15) NOT NULL,
    make             VARCHAR(50) NOT NULL,
    model            VARCHAR(50) NOT NULL,
    manufacture_year INTEGER     NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_vehicles_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE RESTRICT,
    CONSTRAINT uq_vehicles_vin UNIQUE (vin),
    -- ISO 3779: 17 characters, digits and capital letters except I, O and Q
    CONSTRAINT ck_vehicles_vin_format CHECK (vin ~ '^[A-HJ-NPR-Z0-9]{17}$'),
    CONSTRAINT ck_vehicles_manufacture_year CHECK (manufacture_year BETWEEN 1886 AND 2100)
);

CREATE INDEX ix_vehicles_client_id ON vehicles (client_id);

-- -----------------------------------------------------------------------------
-- Appointments
-- -----------------------------------------------------------------------------
CREATE TABLE appointments
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id   BIGINT        NOT NULL,
    start_at     TIMESTAMPTZ   NOT NULL,
    end_at       TIMESTAMPTZ   NOT NULL,
    status       VARCHAR(20)   NOT NULL DEFAULT 'SCHEDULED',
    notes        VARCHAR(1000),
    completed_at TIMESTAMPTZ,
    version      BIGINT        NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_appointments_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id) ON DELETE RESTRICT,
    CONSTRAINT ck_appointments_status CHECK (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_appointments_interval CHECK (end_at > start_at),
    CONSTRAINT ck_appointments_completed_at CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    -- No two non-cancelled appointments of the same vehicle may overlap (half-open intervals).
    CONSTRAINT ex_appointments_vehicle_overlap EXCLUDE USING gist (
        vehicle_id WITH =,
        tstzrange(start_at, end_at, '[)') WITH &&
    ) WHERE (status <> 'CANCELLED')
);

CREATE INDEX ix_appointments_vehicle_id ON appointments (vehicle_id);
CREATE INDEX ix_appointments_start_at ON appointments (start_at);
CREATE INDEX ix_appointments_completed_at ON appointments (completed_at) WHERE status = 'COMPLETED';

-- -----------------------------------------------------------------------------
-- Parts (inventory)
-- -----------------------------------------------------------------------------
CREATE TABLE parts
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)    NOT NULL,
    name       VARCHAR(100)   NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    stock      INTEGER        NOT NULL,
    version    BIGINT         NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_parts_code UNIQUE (code),
    CONSTRAINT ck_parts_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_parts_stock CHECK (stock >= 0)
);

CREATE INDEX ix_parts_stock ON parts (stock);

-- -----------------------------------------------------------------------------
-- Interventions
-- -----------------------------------------------------------------------------
CREATE TABLE interventions
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id   BIGINT         NOT NULL,
    assigned_user_id BIGINT         NOT NULL,
    description      VARCHAR(1000)  NOT NULL,
    labor_cost       NUMERIC(12, 2) NOT NULL,
    version          BIGINT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT fk_interventions_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interventions_assigned_user FOREIGN KEY (assigned_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_interventions_labor_cost CHECK (labor_cost >= 0)
);

CREATE INDEX ix_interventions_appointment_id ON interventions (appointment_id);
CREATE INDEX ix_interventions_assigned_user_id ON interventions (assigned_user_id);

-- -----------------------------------------------------------------------------
-- Parts used by an intervention. unit_price is a snapshot taken when the part was
-- added, so later catalogue price changes never alter the cost of past work.
-- -----------------------------------------------------------------------------
CREATE TABLE intervention_parts
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intervention_id BIGINT         NOT NULL,
    part_id         BIGINT         NOT NULL,
    quantity        INTEGER        NOT NULL,
    unit_price      NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_intervention_parts_intervention FOREIGN KEY (intervention_id) REFERENCES interventions (id) ON DELETE CASCADE,
    CONSTRAINT fk_intervention_parts_part FOREIGN KEY (part_id) REFERENCES parts (id) ON DELETE RESTRICT,
    CONSTRAINT uq_intervention_parts_intervention_part UNIQUE (intervention_id, part_id),
    CONSTRAINT ck_intervention_parts_quantity CHECK (quantity > 0),
    CONSTRAINT ck_intervention_parts_unit_price CHECK (unit_price >= 0)
);

CREATE INDEX ix_intervention_parts_part_id ON intervention_parts (part_id);
